"""Generate the aioovh API packages from the OVHcloud schemas in specs/."""

import json
import keyword
import re
import shutil
import subprocess
import textwrap
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import typer
from pydantic import BaseModel

ROOT = Path(__file__).resolve().parent.parent
SPECS = ROOT / "specs"
PACKAGE = ROOT / "src" / "aioovh"
GENERATED_MARKER = "# Generated by scripts/generate.py from specs/, do not edit."
VERSIONS = {"v1": "/1.0", "v2": "/v2"}
RESERVED_FIELD_NAMES = (
    set(dir(BaseModel)) | set(dir(type(BaseModel))) | {"model_config", "model_fields"}
)
RESERVED_FIELD_NAMES |= {"datetime", "date", "time"}
DASHES = str.maketrans({chr(0x2013): "-", chr(0x2014): "-"})
PAGINATION_HEADERS = {"X-Pagination-Cursor", "X-Pagination-Size"}
STRING_TYPES = {
    "string",
    "password",
    "text",
    "ip",
    "ipv4",
    "ipv6",
    "ipBlock",
    "ipv4Block",
    "ipv6Block",
    "ipInterface",
    "phoneNumber",
    "internationalPhoneNumber",
    "macAddress",
    "uuid",
    "duration",
    "time",
}
SIMPLE_TYPES = {
    **dict.fromkeys(STRING_TYPES, "str"),
    "long": "int",
    "int": "int",
    "double": "float",
    "float": "float",
    "boolean": "bool",
    "datetime": "datetime",
    "date": "date",
    "any": "Any",
    "void": "None",
}


def snake(name: str) -> str:
    name = re.sub(r"[^0-9A-Za-z]+", "_", name)
    name = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name)
    return re.sub(r"_+", "_", name).strip("_").lower()


def pascal(name: str) -> str:
    parts = re.split(r"[^0-9A-Za-z]+", name)
    return "".join(part[:1].upper() + part[1:] for part in parts if part)


def identifier(name: str, reserved: set[str] | frozenset[str] = frozenset()) -> str:
    result = snake(name) or "value"
    if result[0].isdigit():
        result = f"v{result}"
    if keyword.iskeyword(result) or keyword.issoftkeyword(result) or result in reserved:
        result += "_"
    return result


def docstring(*parts: str | None, indent: str) -> str:
    text = "\n\n".join(part.strip() for part in parts if part and part.strip())
    if not text:
        return ""
    text = text.translate(DASHES).replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    lines: list[str] = []
    for paragraph in text.split("\n"):
        lead = paragraph[: len(paragraph) - len(paragraph.lstrip(" "))]
        wrapped = textwrap.wrap(
            paragraph.lstrip(" "),
            88 - len(indent),
            initial_indent=lead,
            subsequent_indent=lead + ("    " if lead else ""),
            break_long_words=False,
        )
        lines.extend(wrapped or [""])
    body = "\n".join(f"{indent}{line}" if line else "" for line in lines)
    if body.rstrip().endswith('"'):
        body += " "
    return f'{indent}"""\n{body}\n{indent}"""\n'


def member_names(values: list[str]) -> list[str]:
    names: list[str] = []
    for value in values:
        name = snake(value).upper() or "EMPTY"
        if name[0].isdigit():
            name = f"_{name}"
        candidate, index = name, 2
        while candidate in names:
            candidate = f"{name}_{index}"
            index += 1
        names.append(candidate)
    return names


@dataclass
class Param:
    name: str
    wire: str
    location: str
    annotation: str
    required: bool
    description: str | None


@dataclass
class Operation:
    method_name: str
    http_method: str
    path: str
    description: str | None
    status: str
    params: list[Param]
    whole_body: bool
    response: str
    authenticated: bool
    paginated: bool


@dataclass
class Module:
    version: str
    resource: str
    name: str
    class_name: str
    models: dict[str, Any]
    apis: list[dict[str, Any]]
    names: dict[str, str] = field(default_factory=dict)
    uses: set[str] = field(default_factory=set)
    operations: list[Operation] = field(default_factory=list)


def split_generic(text: str) -> tuple[str, list[str]]:
    match = re.fullmatch(r"([^<]+)<(.+)>", text)
    if match is None:
        return text, []
    depth, current, args = 0, "", []
    for char in match.group(2):
        if char == "," and depth == 0:
            args.append(current.strip())
            current = ""
            continue
        depth += char == "<"
        depth -= char == ">"
        current += char
    args.append(current.strip())
    return match.group(1), args


class Generator:
    def __init__(self, module: Module) -> None:
        self.module = module
        self.generic_ids = {
            key.split("<", 1)[0]: key
            for key, model in module.models.items()
            if "generics" in model
        }

    def class_name(self, model_id: str) -> str:
        if model_id not in self.module.names:
            candidate = pascal(model_id.split("<", 1)[0].replace(".", "_"))
            taken = set(self.module.names.values()) | {
                self.module.class_name,
                "OVHModel",
            }
            unique, index = candidate, 2
            while unique in taken:
                unique = f"{candidate}{index}"
                index += 1
            self.module.names[model_id] = unique
        return self.module.names[model_id]

    def annotation(self, full_type: str, generics: tuple[str, ...] = ()) -> str:
        text = full_type.strip()
        if ":" in text and not text.startswith("map["):
            alias, base = text.rsplit(":", 1)
            suffix = "[]" * (alias.count("[]") - base.count("[]"))
            return self.annotation(base + suffix, generics)
        if text.startswith("[]"):
            return f"list[{self.annotation(text[2:], generics)}]"
        if text.endswith("[]"):
            return f"list[{self.annotation(text[:-2], generics)}]"
        mapping = re.fullmatch(r"map\[([^\]]+)\](.+)", text)
        if mapping is not None:
            key = self.annotation(mapping.group(1), generics)
            return f"dict[{key}, {self.annotation(mapping.group(2), generics)}]"
        if text in generics:
            return text
        base, arguments = split_generic(text)
        if arguments and base in self.generic_ids:
            name = self.class_name(self.generic_ids[base])
            values = ", ".join(self.annotation(arg, generics) for arg in arguments)
            return f"{name}[{values}]"
        if text in SIMPLE_TYPES:
            simple = SIMPLE_TYPES[text]
            if simple in ("datetime", "date"):
                self.module.uses.add(simple)
            return simple
        if text in self.module.models:
            model = self.module.models[text]
            if model.get("enumType") == "long":
                return "int"
            return self.class_name(text)
        if base in self.generic_ids:
            return self.class_name(self.generic_ids[base]) + "[Any]"
        return "Any"

    def render_models(self) -> str:
        body = self.render_model_classes()
        out = [GENERATED_MARKER, "from __future__ import annotations", ""]
        dates = sorted(self.module.uses & {"date", "datetime"})
        if dates:
            out.append(f"from datetime import {', '.join(dates)}")
        out += ["from typing import Any", "", "from pydantic import Field", ""]
        out += [
            "from aioovh._enums import OpenStrEnum",
            "from aioovh._models import OVHModel",
            "",
        ]
        return "\n".join(out + body) + "\n"

    def render_model_classes(self) -> list[str]:
        out: list[str] = []
        for model_id in sorted(self.module.models):
            model = self.module.models[model_id]
            if "enum" not in model:
                continue
            if model.get("enumType") == "long":
                out += ["", f"type {self.class_name(model_id)} = int", ""]
                continue
            values = [str(value) for value in model["enum"]]
            out += ["", f"class {self.class_name(model_id)}(OpenStrEnum):"]
            doc = docstring(model.get("description"), indent="    ")
            if doc:
                out.append(doc.rstrip("\n"))
            for member, value in zip(member_names(values), values, strict=True):
                out.append(f"    {member} = {value!r}")
            out.append("")
        for model_id in sorted(self.module.models):
            model = self.module.models[model_id]
            if "enum" in model:
                continue
            generics = tuple(model.get("generics") or ())
            type_params = f"[{', '.join(generics)}]" if generics else ""
            out += ["", f"class {self.class_name(model_id)}{type_params}(OVHModel):"]
            doc = docstring(model.get("description"), indent="    ")
            if doc:
                out.append(doc.rstrip("\n"))
            properties = model.get("properties") or {}
            if not properties:
                out.append("    pass")
            seen: set[str] = set()
            for wire, prop in properties.items():
                name = identifier(wire, RESERVED_FIELD_NAMES)
                while name in seen:
                    name += "_"
                seen.add(name)
                annotation = self.annotation(
                    prop.get("fullType") or prop["type"], generics
                )
                optional = prop.get("canBeNull") or annotation == "Any"
                arguments = []
                if optional:
                    if annotation not in ("Any", "None"):
                        annotation += " | None"
                    arguments.append("default=None")
                if name != wire:
                    arguments.append(f"alias={wire!r}")
                if name != wire:
                    value = f" = Field({', '.join(arguments)})"
                elif optional:
                    value = " = None"
                else:
                    value = ""
                out.append(f"    {name}: {annotation}{value}")
                doc = docstring(prop.get("description"), indent="    ")
                if doc:
                    out.append(doc.rstrip("\n"))
            out.append("")
        return out


def method_name(root: str, path: str, http_method: str, response: str) -> str:
    segments = [segment for segment in path[len(root) :].split("/") if segment]
    static = [snake(segment) for segment in segments if not segment.startswith("{")]
    base = "_".join(static) or snake(root.rsplit("/", 1)[-1])
    ends_with_parameter = bool(segments) and segments[-1].startswith("{")
    collection = not ends_with_parameter and response.endswith("[]")
    if http_method == "GET":
        return f"{'list' if collection else 'get'}_{base}"
    if http_method == "POST":
        return f"create_{base}" if collection or not static else base
    verb = {"PUT": "update", "DELETE": "delete", "PATCH": "patch"}[http_method]
    return f"{verb}_{base}"


def build_operations(module: Module, generator: Generator) -> None:
    root = module.resource
    collections = {
        api["path"]
        for api in module.apis
        for operation in api["operations"]
        if operation["httpMethod"] == "GET" and operation["responseType"].endswith("[]")
    }
    names: dict[str, list[Operation]] = {}
    for api in module.apis:
        for raw in api["operations"]:
            http_method = raw["httpMethod"]
            response_type = raw["responseType"]
            if http_method == "POST" and api["path"] in collections:
                response_type += "[]"
            name = identifier(
                method_name(root, api["path"], http_method, response_type)
            )
            params: list[Param] = []
            seen: set[str] = set()
            whole_body = False
            for parameter in raw["parameters"]:
                location = parameter["paramType"]
                wire = parameter.get("name") or ""
                if location == "body" and not wire:
                    whole_body = True
                    wire = "body"
                param_name = identifier(wire)
                while param_name in seen:
                    param_name += "_"
                seen.add(param_name)
                params.append(
                    Param(
                        param_name,
                        wire,
                        location,
                        generator.annotation(
                            parameter.get("fullType") or parameter["dataType"]
                        ),
                        bool(parameter.get("required")) or location == "path",
                        parameter.get("description"),
                    )
                )
            headers = {param.wire for param in params if param.location == "header"}
            response = generator.annotation(raw["responseType"])
            operation = Operation(
                method_name=name,
                http_method=http_method,
                path=VERSIONS[module.version] + api["path"],
                description=raw.get("description"),
                status=raw.get("apiStatus", {}).get("value", "PRODUCTION"),
                params=params,
                whole_body=whole_body,
                response=response,
                authenticated=not raw.get("noAuthentication"),
                paginated=headers >= PAGINATION_HEADERS
                and response.startswith("list["),
            )
            names.setdefault(name, []).append(operation)
            module.operations.append(operation)
    for name, operations in names.items():
        if len(operations) == 1:
            continue
        for operation in operations:
            parameters = [p.name for p in operation.params if p.location == "path"]
            suffix = "_by_" + "_and_".join(parameters) if parameters else ""
            operation.method_name = name + suffix
    final = [operation.method_name for operation in module.operations]
    duplicates = sorted({name for name in final if final.count(name) > 1})
    if duplicates:
        raise SystemExit(
            f"{module.version}.{module.name}: duplicate methods {duplicates}"
        )


def signature(operation: Operation, paginated: bool = False) -> list[str]:
    lines = ["self", "*"]
    params = [
        param
        for param in operation.params
        if not (paginated and param.wire == "X-Pagination-Cursor")
    ]
    for param in sorted(params, key=lambda p: not p.required):
        annotation = param.annotation
        if param.required:
            lines.append(f"{param.name}: {annotation}")
        else:
            if not annotation.endswith("| None") and annotation not in ("Any", "None"):
                annotation += " | None"
            lines.append(f"{param.name}: {annotation} = None")
    return lines if len(lines) > 2 else ["self"]


def request_call(operation: Operation, cursor: bool = False) -> list[str]:
    path_values = [
        f"{param.wire}={param.name}"
        for param in operation.params
        if param.location == "path"
    ]
    path = repr(operation.path)
    if path_values:
        path = f"self._client.path({path}, {', '.join(path_values)})"
    arguments = [repr(operation.http_method), path]
    query = [f"{p.wire!r}: {p.name}" for p in operation.params if p.location == "query"]
    if query:
        arguments.append("params={" + ", ".join(query) + "}")
    if operation.whole_body:
        arguments.append("body=body")
    else:
        body = [
            f"{p.wire!r}: {p.name}" for p in operation.params if p.location == "body"
        ]
        if body:
            arguments.append("body={" + ", ".join(body) + "}")
    headers = []
    for param in operation.params:
        if param.location == "header":
            value = (
                "cursor"
                if cursor and param.wire == "X-Pagination-Cursor"
                else param.name
            )
            headers.append(f"{param.wire!r}: {value}")
    if headers:
        arguments.append("headers={" + ", ".join(headers) + "}")
    if not operation.authenticated:
        arguments.append("auth=False")
    return arguments


def is_model(annotation: str) -> bool:
    return bool(re.fullmatch(r"[A-Z][A-Za-z0-9]*(\[.*\])?", annotation))


def render_operation(operation: Operation, enums: set[str]) -> list[str]:
    out = [f"    async def {operation.method_name}("]
    out += [f"        {entry}," for entry in signature(operation)]
    out.append(f"    ) -> {operation.response}:")
    status = (
        None if operation.status == "PRODUCTION" else f"API status: {operation.status}."
    )
    args = "\n".join(
        f"    {param.name}: {' '.join((param.description or '').split())}"
        for param in operation.params
        if param.description
    )
    doc = docstring(
        f"{operation.http_method} {operation.path}",
        operation.description,
        status,
        f"Args:\n{args}" if args else None,
        indent="        ",
    )
    out.append(doc.rstrip("\n"))
    call = ", ".join(request_call(operation))
    if operation.response == "None":
        out.append(f"        await self._client.request({call})")
    elif operation.response == "Any":
        out.append(f"        return await self._client.request_json({call})")
    else:
        out.append(f"        data = await self._client.request_json({call})")
        if is_model(operation.response) and operation.response not in enums:
            out.append(f"        return {operation.response}.model_validate(data)")
        else:
            out.append(f"        return parse({operation.response}, data)")
    out.append("")
    if operation.paginated:
        out += render_pagination(operation)
    return out


def render_pagination(operation: Operation) -> list[str]:
    item = operation.response[5:-1]
    params = signature(operation, paginated=True)
    name = operation.method_name
    out = [f"    async def {name}_iter("]
    out += [f"        {entry}," for entry in params]
    out.append(f"    ) -> AsyncIterator[{item}]:")
    out.append(
        f'        """Iterate over every item of `{name}`, cursor after cursor."""'
    )
    out.append("")
    page_type = f"tuple[list[{item}], str | None]"
    out.append(f"        async def fetch(cursor: str | None) -> {page_type}:")
    call = ", ".join(request_call(operation, cursor=True))
    out.append(f"            response = await self._client.request({call})")
    out.append(f"            items = parse(list[{item}], response.json())")
    out.append("            return items, response.headers.get(NEXT_CURSOR_HEADER)")
    out.append("")
    out.append("        async for entry in paginate_cursor(fetch):")
    out.append("            yield entry")
    out.append("")
    out.append(f"    async def {name}_all(")
    out += [f"        {entry}," for entry in params]
    out.append(f"    ) -> list[{item}]:")
    out.append(f'        """Every item of `{name}`, all pages read."""')
    forwarded = [
        f"{entry.split(':')[0]}={entry.split(':')[0]}"
        for entry in params
        if entry not in ("self", "*")
    ]
    iterator = f"self.{name}_iter({', '.join(forwarded)})"
    out.append(f"        return [entry async for entry in {iterator}]")
    out.append("")
    return out


def render_api(module: Module) -> str:
    out = [GENERATED_MARKER, "from __future__ import annotations", ""]
    if any(operation.paginated for operation in module.operations):
        out.append("from collections.abc import AsyncIterator")
    dates = sorted(module.uses & {"date", "datetime"})
    if dates:
        out.append(f"from datetime import {', '.join(dates)}")
    out += ["from typing import Any", ""]
    core = ["NEXT_CURSOR_HEADER", "OVHClient", "paginate_cursor", "parse"]
    out.append(f"from aioovh._client import {', '.join(core)}")
    names = sorted(set(module.names.values()))
    if names:
        out.append(f"from aioovh.{module.version}.{module.name}.models import (")
        out += [f"    {name}," for name in names]
        out.append(")")
    out += ["", "", f"class {module.class_name}:"]
    out.append(
        docstring(f"Operations under {module.resource}.", indent="    ").rstrip("\n")
    )
    out += [
        "",
        "    def __init__(self, client: OVHClient) -> None:",
        "        self._client = client",
        "",
    ]
    enums = {
        module.names[model_id]
        for model_id, model in module.models.items()
        if "enum" in model
    }
    for operation in module.operations:
        out += render_operation(operation, enums)
    return "\n".join(out) + "\n"


def render_init(module: Module) -> str:
    names = sorted(set(module.names.values()))
    out = [GENERATED_MARKER]
    exported = list(names)
    if module.operations:
        out.append(
            f"from aioovh.{module.version}.{module.name}.api import {module.class_name}"
        )
        exported.append(module.class_name)
    if names:
        out.append(f"from aioovh.{module.version}.{module.name}.models import (")
        out += [f"    {name}," for name in names]
        out.append(")")
    out += ["", "__all__ = ["]
    out += [f"    {name!r}," for name in sorted(exported)]
    out.append("]")
    return "\n".join(out) + "\n"


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def clean() -> None:
    for version in VERSIONS:
        for init in (PACKAGE / version).glob("*/__init__.py"):
            if init.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
                shutil.rmtree(init.parent)


def main(
    format_code: bool = typer.Option(True, help="Run ruff on the output."),
) -> None:
    clean()
    for version in VERSIONS:
        for spec_path in sorted((SPECS / version).glob("*.json")):
            if spec_path.name == "index.json":
                continue
            spec = json.loads(spec_path.read_text(encoding="utf-8"))
            resource = spec["resourcePath"]
            name = snake(resource)
            module = Module(
                version=version,
                resource=resource,
                name=name,
                class_name=f"{pascal(snake(resource))}{version.upper()}API",
                models=spec.get("models") or {},
                apis=spec.get("apis") or [],
            )
            generator = Generator(module)
            for model_id in module.models:
                generator.class_name(model_id)
            build_operations(module, generator)
            base = PACKAGE / version / name
            models = generator.render_models()
            write(base / "models.py", models)
            if module.operations:
                write(base / "api.py", render_api(module))
            write(base / "__init__.py", render_init(module))
            typer.echo(f"{version}.{name}: {len(module.operations)} operations")
        write(PACKAGE / version / "__init__.py", GENERATED_MARKER + "\n")
    if format_code:
        targets = [str(PACKAGE / version) for version in VERSIONS]
        subprocess.run(["ruff", "check", "--fix", "--quiet", *targets], check=False)
        subprocess.run(["ruff", "format", "--quiet", *targets], check=True)


if __name__ == "__main__":
    typer.run(main)
